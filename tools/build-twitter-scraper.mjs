import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({
  absWorkingDir:root,entryPoints:['integrations/twitter-scraper/browser-entry.js'],
  outfile:'extension/twitter-scraper.bundle.js',bundle:true,platform:'browser',format:'iife',target:'chrome120',
  minify:true,legalComments:'inline',metafile:true,
  // The upstream optional canvas integration is irrelevant in a worker.
  alias:{canvas:'./integrations/twitter-scraper/canvas-stub.js',crypto:'./integrations/twitter-scraper/crypto-shim.js',vm:'./integrations/twitter-scraper/vm-stub.js',jsonify:'./integrations/twitter-scraper/json-shim.js'},
  define:{'process.env.NODE_ENV':'"production"'},
  plugins:[{name:'worker-fetch',setup(builder){
    builder.onLoad({filter:/@acemir\/cssom\/.*\.js$/},async({path})=>({
      contents:(await readFile(path,'utf8')).replaceAll('eval(errorType)','({Error, SyntaxError, TypeError, RangeError})[errorType]'),loader:'js',
    }));
    builder.onLoad({filter:/twitter-scraper\/dist\/default\/esm\/index\.mjs$/},async({path})=>{
      const source=await readFile(path,'utf8');
      if(!source.includes('ClientTransactionClass.create(document)'))throw new Error('Review upstream transaction API before rebuilding.');
      return {contents:source.replace('ClientTransactionClass.create(document)','ClientTransactionClass.create(document, fetchFn)'),loader:'js'};
    });
    builder.onLoad({filter:/x-client-transaction-id\/esm\/transaction\.js$/},async({path})=>{
      let source=await readFile(path,'utf8');
      for(const [from,to]of [
        ['static async create(homePageDocument) {','static async create(homePageDocument, superxFetch) {'],
        ['await instance.initialize();','instance.superxFetch = superxFetch; await instance.initialize();'],
        ['await fetch(onDemandFileUrl)','await this.superxFetch(onDemandFileUrl)'],
      ]){if(!source.includes(from))throw new Error('Review upstream transaction implementation before rebuilding.');source=source.replace(from,to);}
      return {contents:source,loader:'js'};
    });
  }}],
});
const packages=new Map();
for(const name of Object.keys(result.metafile.inputs)) {
  if(!name.includes('node_modules/'))continue;
  const part=name.slice(name.lastIndexOf('node_modules/')+13).split('/');
  const pkg=part[0].startsWith('@')?part.slice(0,2).join('/'):part[0];
  packages.set(pkg,resolve(root,'node_modules',pkg));
}
const notices=['Bundled dependency notices for twitter-scraper.bundle.js. Generated by npm run build:twitter.'];
for(const [name,path]of [...packages].sort()) {
  const info=JSON.parse(await readFile(resolve(path,'package.json'),'utf8'));
  let license='';
  for(const filename of ['LICENSE','LICENSE.md','LICENSE.txt','LICENSE-MIT.txt','LICENSE-MIT','license','license.md']) {
    try{license=await readFile(resolve(path,filename),'utf8');break;}catch{}
  }
  if(!license)throw new Error(`Missing license text for ${name}`);
  notices.push(`\n=== ${name}@${info.version} (${info.license}) ===\n${license}`);
}
await writeFile(resolve(root,'extension/twitter-scraper-LICENSE.txt'),notices.join('\n'));
console.log(`Built browser library; included license notices for ${packages.size} packages.`);
